import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {join,dirname,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {projectTerminology} from '../book/modules/glossary.mjs';
const root=resolve(import.meta.dirname,'..');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
export function glossaryMarkdown(projection) {
 const link=path=>'../../'+path;
 return '# MAT Glossary\n\n<!-- Generated by scripts/build-glossary.mjs; edit data/vocabularies/glossary.json. -->\n\n'+projection.notice+'\n\n[Canonical terminology owner]('+link(projection.owner.path)+') · [Terminology and migration guide](../02-data/14-Canonical-Terminology.md)\n\n'+projection.glossary.map(term=>{
  const variant=term.retained_variants.map(definition=>'### Retained wording\n\n'+definition.definition_markdown+'\n\nOrigin: [retained hover definitions]('+link(definition.origin.snapshot)+'), `'+definition.origin.locator+'`. Source review pending.').join('\n\n');
  return '## '+term.preferred_label+'\n\n'+term.definition_markdown+'\n\nTerm ID: `'+term.term_id+'` · '+(term.domain==='AUTHORED-FRAMEWORK'?'Authored conceptual framework':'MAT editorial reference')+' · Source review pending.'+(term.alternate_labels.length?'\n\nAlternate labels: '+term.alternate_labels.map(label=>'`'+label+'`').join(', ')+'.':'')+'\n\nOrigin: [preserved definition]('+link(term.origin.snapshot)+'), `'+term.origin.locator+'`.'+(variant?'\n\n'+variant:'')+'\n\n---';
 }).join('\n\n')+'\n';
}
export function buildGlossary({repoRoot=root,check=false}={}) {
 const ownerPath='data/vocabularies/glossary.json',bytes=readFileSync(join(repoRoot,ownerPath));
 const owner=JSON.parse(bytes.toString('utf8'));
 const projection=projectTerminology(owner,hash(bytes));
 const origins=owner.migration?.origins;
 if(!origins||Object.keys(origins).sort().join(',')!=='hover,prose'||origins.prose?.original_path!=='docs/08-back-matter/00-Glossary.md'||origins.hover?.original_path!=='book/book.js')throw Error('Both declared migration origins are required.');
 for(const origin of Object.values(origins))if(!/^[a-f0-9]{64}$/.test(origin.sha256??'')||!/^[a-f0-9]{64}$/.test(origin.original_sha256??'')||!/^data\/research\/sources\/[a-z0-9-]+\.(md|json)$/.test(origin.snapshot??''))throw Error('Invalid migration origin metadata.');
 if(origins.prose.original_sha256!==origins.prose.sha256)throw Error('Original prose bytes must remain exact.');
 const retainedLocations=new Set();
 for (const term of owner.terms) for(const definition of [term,...term.retained_variants]) {
  const origin=definition.origin, snapshot=readFileSync(join(repoRoot,origin.snapshot));
  const declared=origin.snapshot===origins.prose.snapshot?origins.prose:origin.snapshot===origins.hover.snapshot?origins.hover:null;
  if(!declared||['snapshot','sha256','original_path','original_sha256'].some(key=>origin[key]!==declared[key]))throw Error('Definition differs from declared migration origin: '+term.term_id);
  const key=origin.snapshot+'#'+origin.locator;
  if(retainedLocations.has(key))throw Error('Duplicate migrated definition origin: '+key);
  retainedLocations.add(key);
  if(hash(snapshot)!==origin.sha256)throw Error('Definition snapshot hash mismatch: '+origin.snapshot);
  if(origin.snapshot.endsWith('.md')){
   const text=snapshot.toString('utf8').replace(/\r\n/g,'\n');
   const heading=origin.locator.replace(/^heading: /,'');
   const section=text.split('## '+heading+'\n\n')[1]?.split(/\n---/)[0]?.trim();
   if(section!==definition.definition_markdown)throw Error('Prose definition differs from preserved source: '+term.term_id);
  }else{
   const source=JSON.parse(snapshot.toString('utf8'));
   if(source.original_sha256!==origin.original_sha256||source.original_path!==origin.original_path||source.table[origin.locator.replace(/^table\./,'')]!==definition.definition_markdown)throw Error('Hover definition differs from preserved source: '+term.term_id);
  }
 }
 for(const origin of Object.values(origins)) {
  const snapshot=readFileSync(join(repoRoot,origin.snapshot),'utf8').replace(/\r\n/g,'\n');
  const locations=origin.snapshot.endsWith('.md')?[...snapshot.matchAll(/^## (.+)$/gm)].map(m=>'heading: '+m[1]):Object.keys(JSON.parse(snapshot).table).map(label=>'table.'+label);
  for(const locator of locations)if(!retainedLocations.has(origin.snapshot+'#'+locator))throw Error('Original definition lost: '+locator);
 }
 const outputs={'docs/08-back-matter/00-Glossary.md':glossaryMarkdown(projection),'book/data/glossary.json':JSON.stringify(projection,null,2)+'\n','data/publication/generated/publication-glossary.json':JSON.stringify(projection,null,2)+'\n'};
 for(const [path,text]of Object.entries(outputs)) {
  const file=join(repoRoot,path);
  if(existsSync(file)&&readFileSync(file,'utf8').replace(/\r\n/g,'\n')===text)continue;
  if(check)throw Error('Glossary projection is stale: '+path);
  mkdirSync(dirname(file),{recursive:true});writeFileSync(file,text);
 }
 return projection;
}
if(import.meta.url===pathToFileURL(process.argv[1]??'').href){
 const check=process.argv.includes('--check');const projection=buildGlossary({check});
 console.log('Glossary: '+projection.glossary.length+' preserved editorial terms; '+(check?'projections and origins verified':'projections generated')+'.');
}
