import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,mkdtempSync,mkdirSync,writeFileSync,rmSync,cpSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {tmpdir} from 'node:os';
import {createHash} from 'node:crypto';
import {projectTerminology,glossaryLookup,normalizeTerm,validateTerminology} from '../../book/modules/glossary.mjs';
import {buildGlossary,glossaryMarkdown} from '../build-glossary.mjs';
const root=join(import.meta.dirname,'../..');
const owner=()=>JSON.parse(readFileSync(join(root,'data/vocabularies/glossary.json'),'utf8'));
const sha=value=>createHash('sha256').update(value).digest('hex');
test('migration retains all original prose and hover wording and explicit unreviewed status',()=>{
 const o=owner();validateTerminology(o);
 const prose=readFileSync(join(root,o.migration.origins.prose.snapshot),'utf8').replace(/\r\n/g,'\n');
 const definitions=[...prose.matchAll(/^## (.+)\n\n([\s\S]*?)(?=\n---\s*(?:\n|$))/gm)];
 assert.equal(definitions.length,22);assert.equal(o.terms.length,33);
 for(const [,label,body]of definitions)assert.equal(o.terms.find(t=>t.preferred_label===label).definition_markdown,body.trim());
 const hover=JSON.parse(readFileSync(join(root,o.migration.origins.hover.snapshot),'utf8')).table;
 const allDefinitions=o.terms.flatMap(t=>[t,...t.retained_variants]);
 assert.equal(Object.keys(hover).length,14);assert.equal(allDefinitions.length,36);
 for(const [label,definition]of Object.entries(hover))assert.ok(allDefinitions.some(t=>t.origin.locator==='table.'+label&&t.definition_markdown===definition));
 assert.ok(o.terms.every(t=>t.review_status==='SOURCE-REVIEW-PENDING'&&t.source_ids.length===0));
 assert.equal(o.terms.find(t=>t.preferred_label==='Causali E').domain,'AUTHORED-FRAMEWORK');
 assert.match(o.terms.find(t=>t.preferred_label==='Evidence Type').definition_markdown,/```text\nMEASURED\nREPLICATED/);
 assert.match(o.terms.find(t=>t.preferred_label==='Confidence').definition_markdown,/Not identical to measurement uncertainty/);
});
test('shared projections resolve explicit aliases without inferring scientific synonyms',()=>{
 const o=owner(),bytes=readFileSync(join(root,'data/vocabularies/glossary.json'));
 const p=projectTerminology(o,sha(bytes)),lookup=glossaryLookup(p);
 assert.deepEqual(projectTerminology(o,sha(bytes)),p);assert.equal(p.owner.sha256,sha(bytes));
 for(const label of ['halflife','Half-life','half life','HALF_LIFE'])assert.equal(lookup.get(normalizeTerm(label)).preferred_label,'Half-life');
 assert.equal(lookup.get(normalizeTerm('Causali-E')),lookup.get('causali e'));
 assert.equal(lookup.get(normalizeTerm('half.life')),undefined);
 assert.equal(lookup.get('species'),undefined);
 assert.match(glossaryMarkdown(p),/MAT:TERM:000001/);assert.match(glossaryMarkdown(p),/Retained wording/);
});
test('ambiguous labels, duplicate identities and fabricated review promotions are rejected',()=>{
 const duplicate=owner();duplicate.terms[1].term_id=duplicate.terms[0].term_id;assert.throws(()=>validateTerminology(duplicate),/identity/);
 const aliases=owner();aliases.terms[0].alternate_labels=['isotope'];assert.throws(()=>validateTerminology(aliases),/label/);
 const review=owner();review.terms[0].review_status='VERIFIED';assert.throws(()=>validateTerminology(review),/editorial status/);
 const path=owner();path.terms[0].origin.snapshot='../secret.md';assert.throws(()=>validateTerminology(path),/origin/);
});
test('builder verifies origin bytes and exact wording and detects stale outputs',t=>{
 const repoRoot=mkdtempSync(join(tmpdir(),'mat-glossary-'));t.after(()=>rmSync(repoRoot,{recursive:true,force:true}));
 const copy=path=>{mkdirSync(dirname(join(repoRoot,path)),{recursive:true});cpSync(join(root,path),join(repoRoot,path));};
 const ownerPath='data/vocabularies/glossary.json';copy(ownerPath);
 const o=owner();for(const origin of Object.values(o.migration.origins))copy(origin.snapshot);
 const first=buildGlossary({repoRoot});assert.equal(first.glossary.length,33);assert.deepEqual(buildGlossary({repoRoot,check:true}),first);
 writeFileSync(join(repoRoot,'book/data/glossary.json'),'{}');assert.throws(()=>buildGlossary({repoRoot,check:true}),/stale/);
 buildGlossary({repoRoot});
 const omitted=owner();delete omitted.migration.origins.hover;writeFileSync(join(repoRoot,ownerPath),JSON.stringify(omitted));
 assert.throws(()=>buildGlossary({repoRoot}),/Both declared migration origins/);
 const originalMetadata=owner();originalMetadata.terms[0].origin.original_sha256='0'.repeat(64);writeFileSync(join(repoRoot,ownerPath),JSON.stringify(originalMetadata));
 assert.throws(()=>buildGlossary({repoRoot}),/declared migration origin/);
 const lost=owner();lost.terms=lost.terms.filter(t=>t.preferred_label!=='Nuclide');writeFileSync(join(repoRoot,ownerPath),JSON.stringify(lost));
 assert.throws(()=>buildGlossary({repoRoot}),/Original definition lost/);
 const altered=owner();altered.terms[0].definition_markdown='An invented replacement';writeFileSync(join(repoRoot,ownerPath),JSON.stringify(altered));
 assert.throws(()=>buildGlossary({repoRoot}),/differs from preserved source/);
 writeFileSync(join(repoRoot,ownerPath),JSON.stringify(o));writeFileSync(join(repoRoot,o.migration.origins.prose.snapshot),'Corrupted source');
 assert.throws(()=>buildGlossary({repoRoot}),/hash mismatch/);
});
