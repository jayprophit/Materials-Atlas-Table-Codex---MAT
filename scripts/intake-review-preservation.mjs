// Legacy intake publication is append-only outside its exact generated paragraph.
import {existsSync,readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {dirname} from 'node:path';

export function replaceNuclearReviewNote(text,note){
 const eol=text.includes('\r\n')?'\r\n':'\n';
 const replacement=note.replace(/\r\n/g,'\n').replace(/\n/g,eol);
 const ownedPattern=/^## Evaluated nuclear data and review\r?\n\r?\nThe \[NUBASE2020 nuclear state catalogue\]\([^\r\n]+-Nuclear-Evaluation\.md\) provides \d+ evaluated states with uncertainties, qualifiers and source-line provenance\.(?: See the \[research intake and claims review\]\([^\r\n]+-Research-Intake\.md\) for the supplied expansion\.)? This dated evaluation does not make the whole material record complete\.\r?\n/;
 const body=replacement.replace(/^\r?\n/,'');
 if(ownedPattern.exec(body)?.[0].length!==body.length)throw new Error('Malformed replacement nuclear note');
 const occurrences=[...text.matchAll(/^## Evaluated nuclear data and review\r?$/gm)];
 if(occurrences.length>1)throw new Error('Ambiguous legacy nuclear review heading; manual review required');
 if(!occurrences.length)return text+replacement;
 const start=occurrences[0].index;
 const tail=text.slice(start);
 const owned=ownedPattern.exec(tail);
 if(!owned)throw new Error('Legacy nuclear paragraph has authored or unfamiliar content; manual review required');
 return text.slice(0,start)+body+tail.slice(owned[0].length);
}

export function flushLegacyIntakeWrites(pending,{allowedParentChanges=new Map()}={}){
 // Validate every proposed destination before the first write. Existing ledgers,
 // registries and bibliographies cannot be silently regenerated by this old tool.
 for(const [path,text]of pending){
  if(!existsSync(path))continue;
  const bytes=readFileSync(path),candidate=Buffer.from(text);
  if(bytes.equals(candidate))continue;
  const allowed=allowedParentChanges.get(path);
  if(!allowed||!bytes.equals(allowed.before)||!candidate.equals(Buffer.from(allowed.after)))throw new Error('Legacy intake would overwrite existing content: '+path+'; reconcile through the current owner before publication');
 }
 let changed=0;
 for(const [path,text]of pending){const bytes=Buffer.from(text);if(existsSync(path)&&readFileSync(path).equals(bytes))continue;mkdirSync(dirname(path),{recursive:true});writeFileSync(path,bytes);changed++;}
 return {changed,planned:pending.size};
}
