import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('source navigation searches actual registry sources and follows recorded usage paths',async({page,request})=>{
 const detailRequests:string[]=[];
 page.on('request',request=>{if(request.url().includes('source-navigation-occurrences'))detailRequests.push(request.url())});
 const response=await request.get('/data/indexes/source-navigation.json');
 expect(response.ok()).toBeTruthy();
 expect(response.headers()['content-type']).toContain('json');
 const report=await response.json();
 const reference=report.sources.find((source:{source_id:string})=>source.source_id==='SRC-000009');
 expect(reference).toBeTruthy();
 const missing=report.sources.find((source:{source_id:string})=>source.source_id==='SRC-000227');
 expect(missing).toBeTruthy();
 await page.goto('/');
 await page.getByRole('button',{name:'Read the selected chapter',exact:true}).click();
 await page.getByText('Browse source navigation',{exact:true}).click();
 const navigation=page.locator('.source-navigation');
 await expect(navigation.getByRole('heading',{name:'Source navigation',exact:true})).toBeVisible();
 await expect(navigation.getByRole('link',{name:'Download exact citation locations',exact:true})).toHaveAttribute('href','./'+report.detail_index.path);
 await navigation.getByRole('textbox',{name:'Search source ID or title'}).fill('SRC-000009');
 const result=navigation.locator('.source-navigation-results > li');
 await expect(result).toHaveCount(1);
 await expect(result).toContainText(reference.title);
 expect(reference.external_links.length).toBeGreaterThan(0);
 await expect(result.getByRole('link',{name:/Original reference/}).first()).toHaveAttribute('href',reference.external_links[0].url);
 await result.getByText(/^Recorded uses \(/).click();
 const usage=reference.usages.find((item:{path:string})=>item.path.startsWith('records/')&&item.path.endsWith('.yaml'));
 expect(usage).toBeTruthy();
 await expect(result.getByRole('link',{name:'Open '+usage.path,exact:true}).first()).toHaveAttribute('href','./'+usage.path);
 if(typeof usage.occurrence_count==='number')await expect(result).toContainText(usage.occurrence_count+' citation occurrences');
 await navigation.getByRole('textbox',{name:'Search source ID or title'}).fill('SRC-000227');
 await expect(result).toHaveCount(1);
 await expect(result).toContainText(missing.title);
 await expect(result).toContainText('Unresolved metadata:');
 await expect(result).toContainText('CITATION-RECOVERED-NEEDS-REVIEW');
 await expect(navigation.getByRole('link',{name:'Canonical source registry',exact:true})).toHaveAttribute('href','./data/registries/sources.yaml');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 expect(detailRequests).toEqual([]);
});

test('source citation exports retain the selected source and leave absent years unresolved',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Read the selected chapter',exact:true}).click();
 await page.getByText('Browse source navigation',{exact:true}).click();
 const navigation=page.locator('.source-navigation');
 await navigation.getByRole('textbox',{name:'Search source ID or title'}).fill('SRC-000009');
 const result=navigation.locator('.source-navigation-results > li');
 await expect(result).toHaveCount(1);
 await result.getByText('Export this source reference',{exact:true}).click();
 const reference=result.getByRole('textbox',{name:'SRC-000009 source reference'});
 await expect(reference).toHaveValue(/SRC-000009/);
 await expect(reference).toHaveValue(/NOT-INDEPENDENT-REPLICATION/);
 await result.getByRole('combobox',{name:'Reference format'}).selectOption('bibtex');
 await expect(reference).toHaveValue(/@misc\{SRC-000009,/);
 await result.getByRole('combobox',{name:'Reference format'}).selectOption('ris');
 await expect(reference).toHaveValue(/ID  - SRC-000009/);
 const downloading=page.waitForEvent('download');
 await result.getByRole('button',{name:'Download reference',exact:true}).click();
 const download=await downloading;expect(download.suggestedFilename()).toBe('SRC-000009-reference.ris');
 const file=await download.path();expect(file).toBeTruthy();
 const exported=await readFile(file!,'utf8');expect(exported).toBe(await reference.inputValue());
 await navigation.getByRole('textbox',{name:'Search source ID or title'}).fill('SRC-000346');
 await expect(result).toHaveCount(1);
 await result.getByText('Export this source reference',{exact:true}).click();
 const partial=result.getByRole('textbox',{name:'SRC-000346 source reference'});
 await expect(partial).toHaveValue(/Year NOT-REPORTED/);
 await expect(partial).toHaveValue(/Certificate issue date: 2017-06-22/);
 await expect(partial).toHaveValue(/INDEPENDENT-REPLICATION-NOT-PERFORMED/);
});

test('source navigation reports an HTML fallback without hiding chapter resources',async({page})=>{
 await page.route('**/data/indexes/source-navigation.json',route=>route.fulfill({status:200,contentType:'text/html',body:'<html><body>Publication fallback</body></html>'}));
 await page.goto('/');
 await page.getByRole('button',{name:'Read the selected chapter',exact:true}).click();
 await page.getByText('Browse source navigation',{exact:true}).click();
 await expect(page.locator('.source-navigation').getByRole('alert')).toContainText('The server returned a page instead of the source navigation index.');
 await expect(page.locator('.resource-section').getByRole('heading',{name:'Sources cited by this chapter',exact:true})).toBeVisible();
 await expect(page.locator('.source-navigation').getByRole('button',{name:'Retry source navigation',exact:true})).toBeVisible();
});
